const normalizeText = (value) => value.replace(/\s+/g, " ").trim();
const spanishText = new Map(Object.entries(translations).map(([english, spanish]) => [normalizeText(english), spanish]));
const englishText = new Map(Object.entries(translations).map(([english, spanish]) => [normalizeText(spanish), english]));
const languageToggle = document.querySelector("[data-language-toggle]");
const savedLanguage = localStorage.getItem("site-language") || "en";

function translatePage(language) {
  const dictionary = language === "es" ? spanishText : englishText;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const textNodes = [];
  let node;

  while ((node = walker.nextNode())) {
    textNodes.push(node);
  }

  textNodes.forEach((textNode) => {
    const value = normalizeText(textNode.nodeValue);
    const translatedValue = dictionary.get(value);
    if (translatedValue) {
      const leadingWhitespace = textNode.nodeValue.match(/^\s*/)[0];
      const trailingWhitespace = textNode.nodeValue.match(/\s*$/)[0];
      textNode.nodeValue = `${leadingWhitespace}${translatedValue}${trailingWhitespace}`;
    }
  });

  document.documentElement.lang = language;
  languageToggle.textContent = language === "es" ? "Switch to English" : "Cambiar a español";
  languageToggle.setAttribute("aria-label", language === "es" ? "Switch to English" : "Switch to Spanish");
  localStorage.setItem("site-language", language);
}

languageToggle.addEventListener("click", () => {
  translatePage(document.documentElement.lang === "es" ? "en" : "es");
});

translatePage(savedLanguage);
